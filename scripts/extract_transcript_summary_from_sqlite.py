#!/usr/bin/env python3
"""
extract_isoform_summary_from_sqlite.py

From LASER read_to_annotated_isoform.sqlite, produce:

1. summary.csv  - sample x pbid x haplotype read counts
   Columns: sample, bulk_pbid, haplotype, associated_gene, associated_transcript, count

2. transcripts.gtf  - all isoforms with key attributes in GTF format

Optimised for millions of reads
"""

import sqlite3
import csv
import argparse
from collections import Counter

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sqlite", required=True, help="read_to_annotated_isoform.sqlite")
    ap.add_argument("--summary_out", required=True, help="Output CSV (summary)")
    ap.add_argument("--gtf_out", required=True, help="Output GTF file (transcripts)")
    args = ap.parse_args()

    conn = sqlite3.connect(args.sqlite)
    cur = conn.cursor()

    print("[INFO] Counting reads efficiently...")
    # Run GROUP BY query ONCE - reused for both summary.csv and counts_by_library.csv
    cur.execute("""
        SELECT sample, pbid, haplotype, SUM(n) as count
        FROM read_counts
        GROUP BY sample, pbid, haplotype
    """)
    counts = cur.fetchall()

    print(f"[INFO] Found {len(counts):,} unique sample-pbid-haplotype combinations.")

    # Fetch transcript info once
    print("[INFO] Loading transcript annotations...")
    cols = [c[1] for c in cur.execute("PRAGMA table_info(transcripts)")]
    pbid_to_info = {}
    for row in cur.execute("SELECT * FROM transcripts"):
        d = dict(zip(cols, row))
        pbid_to_info[d["pbid"]] = d
    print(f"[INFO] Loaded {len(pbid_to_info):,} transcript records.")

    # Write summary CSV
    print(f"[INFO] Writing {args.summary_out}...")
    with open(args.summary_out, "w", newline="") as out:
        w = csv.writer(out)
        w.writerow(["sample", "bulk_pbid", "haplotype", "associated_gene", "associated_transcript", "count"])
        for sample, pbid, haplotype, count in counts:
            tinfo = pbid_to_info.get(pbid, {})
            w.writerow([
                sample,
                pbid,
                haplotype,
                tinfo.get("sqanti_associated_gene", "NA"),
                tinfo.get("sqanti_associated_transcript", "NA"),
                count
            ])

    #  Write transcript_counts_by_library.csv (haplotypes collapsed) 
    print("[INFO] Creating transcript_counts_by_library.csv (haplotypes collapsed)...")

    # Reuse the counts from the query above - no second database scan needed (speed)
    rows = counts

    # 2. Collapse haplotypes
    collapsed = {}
    for sample, pbid, haplotype, count in rows:
        collapsed.setdefault((pbid, sample), 0)
        collapsed[(pbid, sample)] += count

    # 3. Get all unique pbids and samples
    pbids = sorted(set(pbid for pbid, _ in collapsed.keys()))
    samples = sorted(set(sample for _, sample in collapsed.keys()))

    # 4. Write clean CSV
    out_path = "transcript_counts_by_library.csv"
    print(f"[INFO] Writing {out_path}...")

    with open(out_path, "w", newline="") as out:
        w = csv.writer(out)
        header = ["transcript_name", "bulk_pbid", "associated_gene", "associated_transcript"] + samples
        w.writerow(header)

        for pbid in pbids:
            tinfo = pbid_to_info.get(pbid, {})
            gene = tinfo.get("sqanti_associated_gene", "NA")
            transcript = tinfo.get("sqanti_associated_transcript", "NA")
            row = [pbid, pbid, gene, transcript]
            for sample in samples:
                row.append(collapsed.get((pbid, sample), 0))
            w.writerow(row)

    print(f"[INFO] Wrote {out_path} with {len(pbids):,} transcripts x {len(samples)} samples.")


    # Write GTF
    print(f"[INFO] Writing {args.gtf_out}...")
    with open(args.gtf_out, "w") as out:
        out.write("# generated by extract_isoform_summary_from_sqlite.py\n")
        for pbid, d in pbid_to_info.items():
            chrom = d.get("sqanti_chrom") or d.get("orf_chrom", "chrNA")
            start = d.get("orf_transcript_start", "0")
            end = d.get("orf_transcript_end", "0")
            strand = d.get("sqanti_strand") or d.get("orf_strand", ".")
            gene = d.get("sqanti_associated_gene", "NA")
            transcript = d.get("sqanti_associated_transcript", "NA")
            category = d.get("sqanti_structural_category", "NA")

            attributes = (
                f'gene_id "{gene}"; '
                f'transcript_id "{pbid}"; '
                f'structural_category "{category}"; '
                f'source_transcript "{transcript}";'
            )
            out.write(f"{chrom}\tLASER\ttranscript\t{start}\t{end}\t.\t{strand}\t.\t{attributes}\n")

    conn.close()
    print("[INFO] Done!")

if __name__ == "__main__":
    main()
